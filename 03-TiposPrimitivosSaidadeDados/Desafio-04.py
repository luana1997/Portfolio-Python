N = input('Digite algo: ')
print(type(N)) #O tipo primitivo desse valor é?
print(N.isspace()) #Só tem espaços?
print(N.isnumeric()) #É um número?'
print(N.isalpha()) #É alfabético?
print(N.isalnum()) #É alfanumérico?
print(N.isupper()) #Está em maiúsculas?
print (N.islower()) #Está em minúsculas?
print(N.istitle()) #Está capitalizado?